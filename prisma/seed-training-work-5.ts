/**
 * 「／」を改行に変換する。ただし全角カッコの内側の「／」はそのまま残す。
 * （例:「試用期間6ヶ月／その間は契約社員」はカッコ内の補足なので改行すると読めなくなる）
 */
function toLines(text: string): string {
  let depth = 0;
  let out = "";
  for (const ch of text) {
    if (ch === "（") depth++;
    else if (ch === "）") depth = Math.max(0, depth - 1);
    if (ch === "／" && depth === 0) {
      out += "\n";
      continue;
    }
    out += ch;
  }
  return out;
}

